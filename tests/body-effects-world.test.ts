import { afterEach, describe, expect, it } from 'vitest';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DESKTOP_PET_DEFAULTS } from '../src/config.ts';
import { DesktopPetWorld } from '../src/world.ts';
import { FakeHost } from './helpers/fake-host.ts';
import { FakePage } from './helpers/page.ts';
const cleanups: Array<() => Promise<void>> = [];
afterEach(async () => { for (const fn of cleanups.reverse()) await fn(); cleanups.length = 0; });
describe('World body policy transport', () => {
  it('sends persistent policy in init and hot prefs and exposes only current feedback', async () => {
    const cfg = structuredClone(DESKTOP_PET_DEFAULTS);
    Object.assign(cfg, { enabled: true, port: 0 }); cfg.window.enabled = false; cfg.asr.enabled = false;
    cfg.bodyEffects.squash = false;
    const dir = mkdtempSync(join(tmpdir(), 'pet-effects-'));
    const world = new DesktopPetWorld({ cfg, timezone: 'Asia/Shanghai', persist: patch => Object.assign(cfg, patch), runtimesRoot: () => join(dir, 'runtimes'), modelsDir: () => join(dir, 'models') });
    await world.start(new FakeHost());
    cleanups.push(async () => { await world.stop(); rmSync(dir, { recursive: true, force: true }); });
    const page = await FakePage.open(world.petUrl.replace(/\/pet$/, ''));
    cleanups.push(() => page.close());
    expect(page.init.bodyEffects).toEqual({ squash: false, dragStretch: true, breathing: true });
    const report = { status: 'applied', supported: ['squash', 'dragStretch', 'breathing'], values: { ...cfg.bodyEffects } };
    page.send({ t: 'body-effects', figure: cfg.skin.figure ?? '', requested: { ...cfg.bodyEffects }, report });
    await expect.poll(() => (world.petState().bodyEffectsFeedback as any)?.status).toBe('applied');
    const framework = await world.webUi().invoke!('framework', 'state', []) as any;
    expect(framework.definition.id).toBe('desktop-live2d-pet');
    expect(framework.configuration.bodyEffects.observed.status).toBe('applied');
    expect(framework.runtime).toBeNull();
    page.send({ t: 'framework-state', figure: cfg.skin.figure ?? '', snapshot: { definitionId: 'desktop-live2d-pet', schemaVersion: 1, domains: {} } });
    await expect.poll(() => (world.petState().framework as any).runtime?.definitionId).toBe('desktop-live2d-pet');
    await world.webUi().invoke!('framework', 'setBodyEffects', [{ breathing: false }]);
    expect(cfg.bodyEffects.squash).toBe(false);
    expect(world.petState().bodyEffectsFeedback).toBeNull();
    const prefs = await page.next(m => m.t === 'prefs' && (m.bodyEffects as any)?.breathing === false);
    expect(prefs.bodyEffects).toEqual({ squash: false, dragStretch: true, breathing: false });
    page.send({ t: 'body-effects', figure: cfg.skin.figure ?? '', requested: { ...cfg.bodyEffects }, report: { status: 'unsupported', supported: [], values: {} } });
    await expect.poll(() => (world.petState().bodyEffectsFeedback as any)?.status).toBe('unsupported');
  });
});
